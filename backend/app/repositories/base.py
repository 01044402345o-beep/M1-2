"""저장소 인터페이스. 서비스 계층은 이 인터페이스에만 의존한다.

- 운영: firestore.py (Firestore)
- 테스트: memory.py (메모리) — Firebase 키 없이 API 흐름을 검증하기 위함
"""
from typing import Optional, Protocol


class DataRepository(Protocol):
    def list(self, start: Optional[str] = None, end: Optional[str] = None,
             limit: Optional[int] = None, desc: bool = False) -> list[dict]: ...
    def get(self, item_id: str) -> Optional[dict]: ...
    def find_by_date(self, date: str) -> Optional[dict]: ...
    def create(self, data: dict) -> dict: ...
    def update(self, item_id: str, data: dict) -> Optional[dict]: ...
    def delete(self, item_id: str) -> bool: ...


class ConversationRepository(Protocol):
    def list_meta(self, limit: int = 50) -> list[dict]: ...
    def get(self, conv_id: str) -> Optional[dict]: ...
    def create(self, data: dict) -> dict: ...
    def update(self, conv_id: str, data: dict) -> Optional[dict]: ...
    def delete(self, conv_id: str) -> bool: ...
